class I18nEngine {
  constructor() {
    this.currentLang = localStorage.getItem('hasnaa_lang') || 'en';
  }

  init() {
    this.applyLanguage(this.currentLang);
    this.bindEvents();
  }

  getLang() {
    return this.currentLang;
  }

  t(key, replacements = {}) {
    let str = (HASNAA_I18N[this.currentLang] && HASNAA_I18N[this.currentLang][key]) || 
              (HASNAA_I18N['en'] && HASNAA_I18N['en'][key]) || key;
    for (const [rKey, rVal] of Object.entries(replacements)) {
      str = str.replace(`{${rKey}}`, rVal);
    }
    return str;
  }

  applyLanguage(lang) {
    this.currentLang = lang;
    localStorage.setItem('hasnaa_lang', lang);
    
    // Set document level attributes
    document.documentElement.lang = lang;
    document.documentElement.dir = (lang === 'ar' ? 'rtl' : 'ltr');
    
    // Toggle active state on switcher buttons
    document.querySelectorAll('.hn-lang-btn').forEach(btn => {
      const btnLang = btn.getAttribute('data-lang');
      if (btnLang === lang) {
        btn.classList.add('active');
        btn.setAttribute('aria-pressed', 'true');
      } else {
        btn.classList.remove('active');
        btn.setAttribute('aria-pressed', 'false');
      }
    });

    // Translate all standard data-i18n elements
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      el.textContent = this.t(key);
    });

    // Translate placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      el.setAttribute('placeholder', this.t(key));
    });

    // Translate HTML contents if marked
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      const key = el.getAttribute('data-i18n-html');
      el.innerHTML = this.t(key);
    });

    // Dispatch custom event for dynamic catalog re-renders
    window.dispatchEvent(new CustomEvent('hasnaa:langchange', { detail: { lang } }));
  }

  formatPrice(amount) {
    if (this.currentLang === 'ar') {
      // Arabic numeral format
      const arabicDigits = ['٠','١','٢','٣','٤','٥','٦','٧','٨','٩'];
      const formatted = amount.toLocaleString('en-US').replace(/\d/g, d => arabicDigits[d]);
      return `${formatted} ج.م`;
    }
    return `${amount.toLocaleString('en-US')} EGP`;
  }

  /**
   * Generates official WhatsApp inquiry link
   * Official Brand Name: HAS NAA (Never 'HAS NAA Atelier')
   * Bilingual dynamic message matching selected website language
   */
  generateWhatsAppLink(product, selectedColorName = '', selectedSize = '') {
    const phone = "201000000000"; // Official WhatsApp Concierge Hotline
    let message = "";

    if (this.currentLang === 'ar') {
      const prodName = product.name.ar || product.name.en;
      const colorPart = selectedColorName ? ` بلون ${selectedColorName}` : '';
      const sizePart = selectedSize ? `، مقاس: ${selectedSize}` : '';
      const priceFormatted = this.formatPrice(product.price);
      
      message = `مرحباً حسناء، أود الاستفسار عن ${prodName} (الرمز: ${product.sku})${colorPart}${sizePart} - السعر: ${priceFormatted}. هل يمكن تأكيد التوفر؟`;
    } else {
      const prodName = product.name.en;
      const colorPart = selectedColorName ? ` in ${selectedColorName}` : '';
      const sizePart = selectedSize ? `, Size: ${selectedSize}` : '';
      const priceFormatted = `${product.price.toLocaleString('en-US')} EGP`;

      message = `Hello HAS NAA, I would like to inquire about ${prodName} (Ref: ${product.sku})${colorPart}${sizePart} - Price: ${priceFormatted}. Could you please confirm availability?`;
    }

    return `https://wa.me/${phone}?text=${encodeURIComponent(message)}`;
  }

  bindEvents() {
    document.addEventListener('click', e => {
      const btn = e.target.closest('.hn-lang-btn');
      if (btn) {
        const lang = btn.getAttribute('data-lang');
        if (lang && lang !== this.currentLang) {
          this.applyLanguage(lang);
        }
      }
    });
  }
}

